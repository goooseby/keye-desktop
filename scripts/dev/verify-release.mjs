// Read-only verification of Tauri's signed release files before publication.
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {createHash,createPublicKey,verify} from 'node:crypto';
const config=JSON.parse(fs.readFileSync('src-tauri/tauri.conf.json','utf8'));
const dir=process.argv[2]||'.build/cargo/release/bundle/nsis';
const name='Keye_'+config.version+'_x64-setup.exe',file=fs.readFileSync(path.join(dir,name));
const encoded=fs.readFileSync(path.join(dir,name+'.sig'),'utf8').trim();
const manifest=JSON.parse(fs.readFileSync(path.join(dir,'latest.json'),'utf8'));
const platform=manifest.platforms['windows-x86_64'];
assert.equal(manifest.version,config.version);assert.equal(manifest.size,file.length);
assert.equal(platform.url,'https://github.com/goooseby/keye-desktop/releases/download/v'+config.version+'/'+name);
assert.equal(platform.signature,encoded);
assert.equal(manifest.notes,fs.readFileSync('docs/releases/v'+config.version+'.md','utf8').trim());
const keyLines=Buffer.from(config.plugins.updater.pubkey,'base64').toString('utf8').trim().split(/\r?\n/);
const keyBytes=Buffer.from(keyLines[1],'base64');
assert.equal(keyBytes.length,42);
const publicKey=createPublicKey({key:Buffer.concat([Buffer.from('302a300506032b6570032100','hex'),keyBytes.subarray(10)]),format:'der',type:'spki'});
const lines=Buffer.from(encoded,'base64').toString('utf8').trim().split(/\r?\n/);
const signature=Buffer.from(lines[1],'base64'),globalSignature=Buffer.from(lines[3],'base64');
assert.equal(signature.length,74);assert.equal(globalSignature.length,64);
assert.deepEqual(signature.subarray(2,10),keyBytes.subarray(2,10),'Signer matches installed updater key');
assert.equal(signature.subarray(0,2).toString(),'ED','Use prehashed Minisign signatures');
assert.equal(verify(null,createHash('blake2b512').update(file).digest(),publicKey,signature.subarray(10)),true,'Installer signature is valid');
assert.ok(lines[2].startsWith('trusted comment: '));
assert.equal(verify(null,Buffer.concat([signature.subarray(10),Buffer.from(lines[2].slice(17))]),publicKey,globalSignature),true,'Trusted comment signature is valid');
const hash=createHash('sha256').update(file).digest('hex');
console.log(JSON.stringify({version:manifest.version,productName:config.productName,installer:name,bytes:file.length,sha256:hash,signature:'verified with the existing updater public key'},null,2));
